ALTER PROCEDURE [dbo].[SPR_UPD_HORAS_POOL_PRIMERA_VEZ]
    @PI_IDASIGNACION BIGINT,
    @PI_CANTIDADHORAS DECIMAL(10,2)
AS
BEGIN
    DECLARE @HOR_NID BIGINT;
    DECLARE @HorasActuales DECIMAL(10,2);
 
    SELECT @HOR_NID = HOR_NID FROM TBL_TASIGNACION WHERE ASG_NID = @PI_IDASIGNACION;
    SELECT @HorasActuales = HOR_NCANTIDAD FROM TBL_THORASASIGNADAS WHERE HOR_NID = @HOR_NID;
 
    IF @HorasActuales IS NOT NULL
    BEGIN
        RAISERROR('Las horas de este pool ya fueron asignadas. Usa Ampliación para modificarlas.', 16, 1);
        RETURN;
    END
 
    UPDATE TBL_THORASASIGNADAS
    SET HOR_NCANTIDAD = @PI_CANTIDADHORAS
    WHERE HOR_NID = @HOR_NID;
 
    SELECT @@ROWCOUNT AS Filas;
END