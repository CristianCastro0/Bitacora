ALTER PROCEDURE [dbo].[SPR_INS_ASIGNACION]
@PI_CANTIDADHORAS DECIMAL(10,2) = NULL,
@PI_IDROL BIGINT,
@PI_USUARIO BIGINT,
@PI_IDESTADO BIGINT,
@PI_IDTICKET BIGINT
AS
BEGIN
    SET NOCOUNT ON;
 
    DECLARE @HOR_NID BIGINT;
 
    SELECT TOP 1 @HOR_NID = A.HOR_NID
    FROM TBL_TASIGNACION A
    INNER JOIN TBL_THORASASIGNADAS H ON H.HOR_NID = A.HOR_NID
    WHERE A.TIC_NID = @PI_IDTICKET AND H.ROL_NID = @PI_IDROL;
 
    IF @HOR_NID IS NULL
    BEGIN
        INSERT INTO TBL_THORASASIGNADAS (ROL_NID, HOR_NCANTIDAD)
        VALUES (@PI_IDROL, @PI_CANTIDADHORAS); 
 
        SET @HOR_NID = SCOPE_IDENTITY();
    END
    ELSE IF @PI_CANTIDADHORAS IS NOT NULL AND NOT EXISTS (
        SELECT 1 FROM TBL_THORASASIGNADAS WHERE HOR_NID = @HOR_NID AND HOR_NCANTIDAD IS NOT NULL
    )
    BEGIN
        -- El pool ya existía (ej. el de Senior, creado vacío al cargar
        -- el CSV) pero todavía no tenía horas — se completa aquí, la
        -- primera vez que llega un valor real.
        UPDATE TBL_THORASASIGNADAS
        SET HOR_NCANTIDAD = @PI_CANTIDADHORAS
        WHERE HOR_NID = @HOR_NID;
    END
 
    INSERT INTO TBL_TASIGNACION
    (ASG_DFECHA_ASIGNADA, TIC_NID, USU_NID, ESA_NID, HOR_NID)
    VALUES
    (GETDATE(), @PI_IDTICKET, @PI_USUARIO, @PI_IDESTADO, @HOR_NID);
 
    SELECT @@ROWCOUNT AS Filas;
END