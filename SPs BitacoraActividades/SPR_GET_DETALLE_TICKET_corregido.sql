ALTER PROCEDURE [dbo].[SPR_GET_DETALLE_TICKET]
@PI_IDTICKET BIGINT,
@PI_IDUSUARIO BIGINT
AS
BEGIN
    SET NOCOUNT ON;
 
    SELECT
        t.TIC_NID AS Id,
        a.ASG_NID AS IdAsignacion,
        p.TIP_CTIPO AS Tipo,
        t.TIC_CCODIGO AS Codigo,
        t.TIC_DFECHA_CREACION AS Fecha,
        t.TIC_CDESCRIPCION AS Descripcion,
        h.HOR_NCANTIDAD AS HorasAsignadas,
        h.ROL_NID AS IdRol,
        u.USU_NID AS IdColaborador,
        n.NOM_CNOMBRE1 + ' ' + n.NOM_CAPELLIDO1 AS NombreColaborador,
        t.ETA_NID AS IdEtapa,
        e.ETA_CNOMBRE AS Etapa,
        CASE WHEN u.USU_NID = @PI_IDUSUARIO THEN 1 ELSE 0 END AS EsUsuarioActual
    FROM TBL_TTICKET t
    INNER JOIN TBL_TASIGNACION a ON t.TIC_NID = a.TIC_NID
    INNER JOIN TBL_RTIPO p ON p.TIP_NID = t.TIP_NID
    INNER JOIN TBL_RUSUARIO u ON u.USU_NID = a.USU_NID
    INNER JOIN TBL_RNOMBRE n ON n.NOM_NID = u.NOM_NID
    INNER JOIN TBL_RETAPA e ON e.ETA_NID = t.ETA_NID
    INNER JOIN TBL_THORASASIGNADAS h ON h.HOR_NID = a.HOR_NID
    WHERE t.TIC_NID = @PI_IDTICKET
END